#!/usr/bin/env node
// Builds src/data/lineagesEA.ts from the D-PLACE Ethnographic Atlas (CLDF).
//
//   git clone --depth 1 https://github.com/D-PLACE/dplace-dataset-ea /tmp/ea
//   node scripts/build-lineages.mjs /tmp/ea/cldf
//
// Run it again only when D-PLACE publishes a new release — the Atlas is an
// ethnographic record, not a live feed. Licence: CC BY-NC 4.0 (attributed in
// the panel). Variables used:
//   EA043 Descent: major type  ·  EA012 Marital residence  ·  EA074 Land inheritance

import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = process.argv[2]
if (!dir) {
  console.error('usage: node scripts/build-lineages.mjs <path-to-dplace-dataset-ea/cldf>')
  process.exit(1)
}

// Minimal RFC-4180 CSV parser (quoted fields, embedded commas/quotes/newlines).
function parseCsv(text) {
  const rows = []
  let row = [], field = '', q = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (q) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++ } else q = false
      } else field += c
    } else if (c === '"') q = true
    else if (c === ',') { row.push(field); field = '' }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++
      row.push(field); rows.push(row); row = []; field = ''
    } else field += c
  }
  if (field || row.length) { row.push(field); rows.push(row) }
  const [head, ...body] = rows.filter((r) => r.length > 1)
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])))
}

const read = (f) => parseCsv(readFileSync(join(dir, f), 'utf8'))

const vals = {}
for (const r of read('data.csv')) {
  if (r.Var_ID === 'EA043' || r.Var_ID === 'EA012' || r.Var_ID === 'EA074') {
    const code = Number(r.Code_ID.split('-').pop())
    ;(vals[r.Soc_ID] ??= {})[r.Var_ID] = Number.isFinite(code) ? code : 0
  }
}

// Residence → five groups. 'a' (avunculocal) = the couple lives with the
// husband's maternal uncle: matrilineal kin, but male-led.
const RES = { 5: 'm', 9: 'm', 1: 'a', 3: 'a', 4: 'a', 8: 'p', 10: 'p', 2: 'b', 6: 'b', 7: 'b' }

const out = []
for (const s of read('societies.csv')) {
  const lat = Number(s.Latitude), lon = Number(s.Longitude)
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue
  const v = vals[s.ID] ?? {}
  out.push([
    Math.round(lat * 10) / 10,
    Math.round(lon * 10) / 10,
    v.EA043 ?? 0,
    RES[v.EA012] ?? '',
    v.EA074 ?? 0,
    s.Name,
  ])
}

const here = dirname(fileURLToPath(import.meta.url))
const target = join(here, '..', 'src', 'data', 'lineagesEA.ts')
const body =
  `// GENERATED by scripts/build-lineages.mjs from the D-PLACE Ethnographic Atlas\n` +
  `// (CC BY-NC 4.0). Do not edit by hand.\n` +
  `// Row: [lat, lon, descent EA043, residence group, land inheritance EA074, name]\n` +
  `// descent: 1 patrilineal · 2 duolateral · 3 matrilineal · 4 quasi-lineages · 5 ambilineal · 6 bilateral · 7 mixed · 0 unknown\n` +
  `// residence: m with wife's kin · a with husband's maternal uncle · p with husband's kin · b either/neolocal/separate · '' unknown\n` +
  `// land: 1 no individual land · 2 to sister's sons · 3 to matrilineal heirs · 4 children, less to daughters · 5 children of either sex · 6 patrilineal heirs · 7 sons · 0 unknown\n` +
  `export type EARow = [number, number, number, '' | 'm' | 'a' | 'p' | 'b', number, string]\n\n` +
  `export const EA_SOCIETIES: EARow[] = [\n` +
  out.map((r) => '  ' + JSON.stringify(r) + ',').join('\n') +
  `\n]\n`
writeFileSync(target, body)
console.log(`wrote ${out.length} societies → ${target}`)
